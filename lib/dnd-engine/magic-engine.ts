function getRandom<T>(arr: T[]): T {
  return arr[Math.floor(Math.random() * arr.length)];
}

export function generateCustomSpell(level: number = 3): CustomSpell {
  const mage = getRandom(ANCIENT_MAGES);
  const element = getRandom(ELEMENTS_AND_THEMES);
  const form = getRandom(SPELL_FORMS);
  const debuff = getRandom(DEBUFF_EFFECTS);

  const name = `${element.name} ${form.form} ${mage}`;

  const diceCount = Math.max(1, level * 2 + 1);
  const avgDamage = Math.round(diceCount * 3.5);
  const damageFormula = `${diceCount}d6 ${element.damageType}`;

  let saveOrAttack = 'Спасбросок Ловкости (на половину урона)';
  if (element.school === 'Некромантия (Necromancy)') {
    saveOrAttack = 'Спасбросок Телосложения';
  } else if (element.school === 'Очарование (Enchantment)') {
    saveOrAttack = 'Спасбросок Мудрости';
  } else if (form.form === 'Стрела' || form.form === 'Хлыст') {
    saveOrAttack = 'Дальнобойная атака заклинанием';
  }

  return {
    name,
    level,
    school: element.school,
    castingTime: '1 действие',
    range: form.area.includes('дистанция') ? '120 футов' : '60 футов',
    components: 'В, С, М (щепотка серы или осколок зачарованного кварца)',
    duration: 'Мгновенная (или 1 минута с концентрацией для эффектов)',
    targetArea: form.area,
    saveOrAttack,
    damageOrEffect: `${avgDamage} (${damageFormula}) урона`,
    description: `Заклинатель концентрирует тайную энергию и высвобождает ее в виде [${form.form}]. Все существа в области поражения [${form.area}] должны совершить ${saveOrAttack}. При провале они получают ${damageFormula} урона. Дополнительный эффект: ${debuff}`,
    higherLevels: `При сотворении ячейкой ${level + 1} уровня или выше урон увеличивается на 1d6 за каждый уровень ячейки выше ${level}.`,
    ancientCreator: mage,
  };
}

