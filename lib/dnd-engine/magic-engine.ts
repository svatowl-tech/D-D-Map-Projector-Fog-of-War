export function rollWildMagicSurge(): WildMagicSurge {
  const d100Roll = Math.floor(Math.random() * 100) + 1;
  const surge = getRandom(WILD_MAGIC_EFFECTS);
  return {
    d100Roll,
    effect: surge.effect,
    visualTag: surge.visualTag,
    category: surge.category,
  };
}
