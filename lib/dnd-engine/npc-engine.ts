function getRandom<T>(arr: T[]): T {
  return arr[Math.floor(Math.random() * arr.length)];
}

export function generateSocialNPC(presetClass?: string): SocialNPC {
  const gender = Math.random() < 0.5 ? 'Мужской' : 'Женский';
  const firstName = gender === 'Мужской' ? getRandom(FIRST_NAMES_MALE) : getRandom(FIRST_NAMES_FEMALE);
  const surname = getRandom(SURNAMES);
  const name = `${firstName} ${surname}`;

  const socialClass = presetClass || getRandom(SOCIAL_CLASSES);
  const occupation = getRandom(OCCUPATIONS_BY_CLASS[socialClass] || OCCUPATIONS_BY_CLASS['Ремесленник']);
  const race = getRandom(RACES);
  const age = getRandom(AGES);

  const charismaSecret = getRandom(SECRETS_BY_SKILL);
  const quote = `«${getRandom([
    'Не суй нос туда, куда не просят, чужеземец, если жизнь дорога.',
    'Золото говорит громче любых молитв и клятв чести.',
    'Я лишь делаю свою работу, и мне нет дела до чужих бед.',
    'Если вы ищете приключений на свою голову — вы пришли по верному адресу.',
    'Стены этого города имеют уши, а тени — острые кинжалы.',
  ])}»`;

  return {
    name,
    gender,
    race,
    age,
    socialClass,
    occupation,
    appearance: {
      features: getRandom(APPEARANCE_FEATURES),
      clothing: getRandom(CLOTHING_STYLES),
      mannerism: getRandom(MANNERISMS),
      speechQuirk: getRandom(SPEECH_QUIRKS),
    },
    alignment: getRandom(ALIGNMENTS),
    ideal: getRandom(IDEALS),
    bond: getRandom(BONDS),
    flaw: getRandom(FLAWS),
    disposition: getRandom(DISPOSITIONS),
    charismaCheckSecret: charismaSecret,
    rumorOrHook: getRandom(RUMORS_AND_HOOKS),
    dialogueQuote: quote,
  };
}
